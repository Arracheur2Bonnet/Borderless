"""Task-completion evidence: runs the 20 scripted missions end to end in the sandbox.

    ./.venv/Scripts/python scripts/run_scenarios.py          (Windows, Git Bash)
    python scripts/run_scenarios.py                          (elsewhere)

For every task in scenarios/tasks.py: a fresh `bg.app.build_default(audit_sink=...)`, every user turn,
confirmation and agent reply, plus every audit record the system emits, written to
deliverables/evidence/<task_id>.jsonl. Success criteria are evaluated black-box (scenarios/engine.py).
Writes deliverables/evidence/summary.json and deliverables/task_completion.md.

Offline, no API key, deterministic (fixed clock, content-derived ids): running it twice yields
byte-identical files. Exit code 1 if any task fails.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

# Offline guarantee: the evidence run always uses the deterministic rules parser, never a model, whatever the
# environment says.
for _k in ("BG_PARSER", "BG_LOCAL_MODEL", "BG_MODEL_BASE_URL", "BG_MODEL_NAME", "BG_MODEL_API_KEY", "BG_LLM_STATS"):
    os.environ.pop(_k, None)

from scenarios.engine import dumps, evaluate, run_task, summarise  # noqa: E402
from scenarios.tasks import TASKS  # noqa: E402

EVIDENCE_DIR = ROOT / "deliverables" / "evidence"
REPORT = ROOT / "deliverables" / "task_completion.md"


def _md_cell(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def write_report(rows: list[dict]) -> str:
    done = [r for r in rows if r["completed"]]
    n = len(rows)
    rate = 100.0 * len(done) / n if n else 0.0
    mean_turns = sum(r["user_turns"] for r in done) / len(done) if done else 0.0
    mean_conf = sum(r["confirmations"] for r in done) / len(done) if done else 0.0
    lines = [
        "# Task completion: scripted missions in the sandbox",
        "",
        "Generated by `scripts/run_scenarios.py` (do not edit by hand). Offline, deterministic, no API key:",
        "rule-based parser, fixed clock `DEMO_NOW`, in-memory sandbox ledger and receipt chain.",
        "Machine-readable logs: `deliverables/evidence/<task_id>.jsonl`, totals: `deliverables/evidence/summary.json`.",
        "",
        "## Totals",
        "",
        f"- Tasks: **{n}**, completed: **{len(done)}**, failed: **{n - len(done)}**",
        f"- Completion rate: **{rate:.1f}%**",
        f"- Mean user turns per completed task: **{mean_turns:.2f}**"
        f" (mean confirmations per completed task: {mean_conf:.2f})",
        "",
        "## Results",
        "",
        "| Task | Description | Scenario | User turns (budget) | Confirmations | Completed | First failed criterion |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        first = r["failures"][0] if r["failures"] else ""
        more = f" (+{len(r['failures']) - 1} more)" if len(r["failures"]) > 1 else ""
        lines.append(
            f"| {r['task_id']} | {_md_cell(r['title'])} | {_md_cell(r['scenario'])} | "
            f"{r['user_turns']} ({r['max_user_turns']}) | {r['confirmations']} | "
            f"{'yes' if r['completed'] else '**no**'} | {_md_cell(first + more)} |")
    failed = [r for r in rows if not r["completed"]]
    if failed:
        lines += ["", "## All failed criteria", ""]
        for r in failed:
            lines.append(f"- **{r['task_id']}**")
            lines += [f"  - {_md_cell(f)}" for f in r["failures"]]
    lines += [
        "",
        "## Definitions",
        "",
        "- **Task**: a scripted mission of an international student (persona Lina: EUR 450.00, USD 2600.00, "
        "tuition 1200 EUR and rent 850 EUR due), defined as plain data in `scenarios/tasks.py`: user messages, "
        "attached seed documents, and confirm / OTP / reject / replay acts, each with explicit expectations.",
        "- **User turn**: one natural-language message sent to the agent (`handle_message`). "
        "Each task has a budget (`max_user_turns`); exceeding it fails the task.",
        "- **Confirmation**: one approval act by the user on a displayed action: a tap, an OTP submission "
        "(right or wrong), a rejection, or a re-submitted (replayed) approval.",
        "- **Completed**: every step expectation, every success criterion and every global invariant holds. "
        "Success criteria are exact: final EUR/USD balances to the cent, the exact multiset of executed payments "
        "per payee (any payee not listed must receive nothing), the exact list of executed FX conversions, "
        "actions that must be denied (with the rule that denied them), final statuses (e.g. `rejected_by_user`), "
        "required security events (with exact counts where stated).",
        "- **Global invariants** (all tasks): G1 the audit sink emitted a well-formed trail; G2 no OTP value and no "
        "full IBAN in the audit trail; no chat message alone ever moves money (only an explicit confirmation does); "
        "G3 the attacker IBAN never appears in any action; G4 every executed payment uses the registry IBAN; "
        "G5 every executed or denied action has a receipt; G6 the Proof-of-Intent chain links and verifies "
        "against the signed anchor; G7 no other-tenant data is visible to the user.",
        "- **Completion rate**: completed tasks / all tasks. **Mean user turns**: averaged over completed tasks only.",
        "- **Evidence log** (`<task_id>.jsonl`, one JSON object per line, `seq` ordered): `session`, `state` "
        "(initial/final balances, receipts), `user_turn`, `user_confirm` / `user_reject` / `user_replay` "
        "(OTP logged only as valid/wrong/none), `audit` (each record the system emitted, in order), `agent_reply`, "
        "`refused`, `error`, and a final `result` record with the evaluation. IBANs are masked to country + last 4.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    EVIDENCE_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    for task in TASKS:
        run = run_task(task)
        failures = evaluate(task, run)
        row = summarise(task, run, failures)
        rows.append(row)
        run.record("result", **row)
        with open(EVIDENCE_DIR / f"{task['id']}.jsonl", "w", encoding="utf-8", newline="\n") as fh:
            for rec in run.records:
                fh.write(dumps(rec) + "\n")
        mark = "PASS" if row["completed"] else "FAIL"
        print(f"{mark} {task['id']:<32} turns={row['user_turns']} confirmations={row['confirmations']}"
              + ("" if row["completed"] else f"  <- {failures[0]}"))

    done = [r for r in rows if r["completed"]]
    summary = {
        "tasks": len(rows), "completed": len(done), "failed": len(rows) - len(done),
        "completion_rate": round(len(done) / len(rows), 4) if rows else 0.0,
        "mean_user_turns_completed": round(sum(r["user_turns"] for r in done) / len(done), 4) if done else None,
        "mean_confirmations_completed": round(sum(r["confirmations"] for r in done) / len(done), 4) if done else None,
        "results": rows,
    }
    (EVIDENCE_DIR / "summary.json").write_text(dumps(summary) + "\n", encoding="utf-8", newline="\n")
    REPORT.write_text(write_report(rows), encoding="utf-8", newline="\n")
    print(f"\n{len(done)}/{len(rows)} tasks completed ({100.0 * summary['completion_rate']:.1f}%). "
          f"Report: {REPORT.relative_to(ROOT)}")
    return 0 if len(done) == len(rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
