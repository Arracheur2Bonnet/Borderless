// Measures the recorded voice-over clips and writes src/voiceover.json, which re-times the film.
//
//   public/voiceover/<segment id>.mp3   one clip per segment (ids in src/timeline.json), any subset
//   public/music.mp3                    optional music bed (mixed low under the voice)
//
// A segment then lasts max(default seconds, clip + voicePaddingSec): the voice never gets cut, and the
// animation inside each segment keeps its own timing. Run `npm run sync-voice`, then `npm run render`.
import {execFileSync} from 'node:child_process';
import {createRequire} from 'node:module';
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const timeline = JSON.parse(readFileSync(join(root, 'src', 'timeline.json'), 'utf8'));
// Remotion ships ffprobe in its platform compositor package; it is called directly, without a shell.
const require = createRequire(import.meta.url);
function ffprobePath() {
  const pkg = `@remotion/compositor-${process.platform}-${process.arch}${process.platform === 'win32' ? '-msvc' : process.platform === 'linux' ? '-gnu' : ''}`;
  try {
    return join(dirname(require.resolve(`${pkg}/package.json`)), process.platform === 'win32' ? 'ffprobe.exe' : 'ffprobe');
  } catch {
    return 'ffprobe';                                  // fall back to an ffprobe on PATH
  }
}
const FFPROBE = ffprobePath();

function seconds(file) {
  const out = execFileSync(FFPROBE, ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file], {encoding: 'utf8'});
  const s = parseFloat(out.trim().split(/\s+/).pop());
  if (!Number.isFinite(s) || s <= 0) throw new Error(`could not read the duration of ${file}: ${out}`);
  return Math.round(s * 1000) / 1000;
}

const durations = {};
let total = 0;
for (const seg of timeline.segments) {
  const file = join(root, 'public', 'voiceover', `${seg.id}.mp3`);
  let len = seg.seconds;
  if (existsSync(file)) {
    durations[seg.id] = seconds(file);
    len = Math.max(seg.seconds, durations[seg.id] + timeline.voicePaddingSec);
    const flag = durations[seg.id] + timeline.voicePaddingSec > seg.seconds ? '  (segment lengthened)' : '';
    console.log(`${seg.id.padEnd(16)} voice ${durations[seg.id].toFixed(2)} s, target ${seg.seconds} s${flag}`);
  } else {
    console.log(`${seg.id.padEnd(16)} no clip, keeps ${seg.seconds} s`);
  }
  total += len;
}
const music = existsSync(join(root, 'public', 'music.mp3'));
writeFileSync(join(root, 'src', 'voiceover.json'), JSON.stringify({
  _comment: 'Generated by `npm run sync-voice` from public/voiceover/*.mp3 and public/music.mp3. Empty = default timings, silent video.',
  durations,
  music,
}, null, 2) + '\n');
console.log(`\n${Object.keys(durations).length}/${timeline.segments.length} clips, music: ${music ? 'yes' : 'no'}, film length ${total.toFixed(1)} s`);
